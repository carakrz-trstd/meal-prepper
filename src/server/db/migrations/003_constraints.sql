-- Epic 3: participants with dietary restrictions, ingredient blacklist, dietary keyword mapping,
-- last suggestion preferences and the participants ticked for each planned meal.
CREATE TABLE participant (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  name TEXT NOT NULL CHECK (length(trim(name)) > 0)
);

CREATE TABLE participant_restriction (
  participant_id INTEGER NOT NULL REFERENCES participant(id) ON DELETE CASCADE,
  restriction TEXT NOT NULL CHECK (restriction IN ('vegetarian', 'vegan', 'gluten-free', 'lactose-free', 'nut-free', 'seafood-free')),
  PRIMARY KEY (participant_id, restriction)
);

CREATE TABLE blacklist_item (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  term TEXT NOT NULL UNIQUE CHECK (length(term) > 0)
);

-- Data-driven dietary mapping (NFR-3): forbidden keyword = violates, safe keyword = verified, no match = unknown.
CREATE TABLE restriction_keyword (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  restriction TEXT NOT NULL CHECK (restriction IN ('vegetarian', 'vegan', 'gluten-free', 'lactose-free', 'nut-free', 'seafood-free')),
  keyword TEXT NOT NULL,
  effect TEXT NOT NULL CHECK (effect IN ('forbidden', 'safe')),
  UNIQUE (restriction, keyword, effect)
);

CREATE TABLE suggestion_prefs (
  id INTEGER PRIMARY KEY CHECK (id = 1),
  calorie_limit INTEGER NULL,
  budget_limit REAL NULL,
  time_limit INTEGER NULL,
  participant_ids TEXT NOT NULL DEFAULT '[]'
);

CREATE TABLE planned_meal_participant (
  planned_meal_id INTEGER NOT NULL REFERENCES planned_meal(id) ON DELETE CASCADE,
  participant_id INTEGER NOT NULL REFERENCES participant(id) ON DELETE CASCADE,
  PRIMARY KEY (planned_meal_id, participant_id)
);

